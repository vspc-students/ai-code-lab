def get_client():
    global _client

    if _client is None:
        api_key = __import__("os").getenv("OPENAI_API_KEY")

        if not api_key:
            raise ValueError("OPENAI_API_KEY is not set")

        _client = OpenAI(api_key=api_key)

    return _client


